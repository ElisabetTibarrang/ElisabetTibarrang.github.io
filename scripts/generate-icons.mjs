#!/usr/bin/env node
// scripts/generate-icons.mjs

import { promises as fs } from "node:fs";
import path from "node:path";
import process from "node:process";
import fg from "fast-glob";
import { optimize } from "svgo";
import svgConfig from "../src/config/svg.mjs";

const root = process.cwd();

const XML_DECLARATION_RE = /^\s*<\?xml[\s\S]*?\?>\s*/i;
const DOCTYPE_RE = /^\s*<!doctype[\s\S]*?>\s*/i;

function toPosix(value) {
  return value.split(path.sep).join("/");
}

function fromRoot(...parts) {
  return path.join(root, ...parts);
}

function slugifyName(filePath) {
  return path
    .basename(filePath, path.extname(filePath))
    .toLowerCase()
    .trim()
    .replace(/[\s_]+/g, "-")
    .replace(/[^a-z0-9-]/g, "")
    .replace(/-+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function normalizeSvg(svg) {
  return String(svg || "")
    .replace(XML_DECLARATION_RE, "")
    .replace(DOCTYPE_RE, "")
    .trim();
}

function extractSvgParts(svg) {
  const normalized = normalizeSvg(svg);
  const openTagMatch = normalized.match(/<svg\b([^>]*)>/i);
  const bodyMatch = normalized.match(/<svg\b[^>]*>([\s\S]*?)<\/svg>\s*$/i);

  const attrs = openTagMatch?.[1] || "";
  const viewBox =
    attrs.match(/\bviewBox=(['"])(.*?)\1/i)?.[2] ||
    attrs.match(/\bviewbox=(['"])(.*?)\1/i)?.[2] ||
    "0 0 24 24";

  const body = (bodyMatch?.[1] || "").trim();

  return { viewBox, body };
}

function prefixSvgIds(svg, prefix) {
  return String(svg || "")
    .replace(/\bid=(["'])([^"']+)\1/g, (_, q, id) => {
      if (String(id).startsWith(`${prefix}-`)) return `id=${q}${id}${q}`;
      return `id=${q}${prefix}-${id}${q}`;
    })
    .replace(/url\(#([^)]+)\)/g, (_, id) => {
      if (String(id).startsWith(`${prefix}-`)) return `url(#${id})`;
      return `url(#${prefix}-${id})`;
    })
    .replace(/\bhref=(["'])#([^"']+)\1/g, (_, q, id) => {
      if (String(id).startsWith(`${prefix}-`)) return `href=${q}#${id}${q}`;
      return `href=${q}#${prefix}-${id}${q}`;
    })
    .replace(/\bxlink:href=(["'])#([^"']+)\1/g, (_, q, id) => {
      if (String(id).startsWith(`${prefix}-`)) return `xlink:href=${q}#${id}${q}`;
      return `xlink:href=${q}#${prefix}-${id}${q}`;
    });
}

function applyMonoCurrentColor(svg) {
  if (!svgConfig.svgo?.mono?.currentColor) return svg;

  const converted = String(svg || "").replace(
    /\s(fill|stroke)=(['"])(?!none\b|currentColor\b|url\()[^'"]*\2/gi,
    " $1=$2currentColor$2"
  );

  if (/^<svg\b[^>]*\sfill=/i.test(converted)) return converted;
  return converted.replace(/^<svg\b/i, '<svg fill="currentColor"');
}

function svgoPlugins(kind) {
  return (
    svgConfig.svgo?.[kind]?.plugins ||
    svgConfig.svgo?.common?.plugins ||
    ["preset-default", "removeDimensions"]
  );
}

async function optimizeSvg(source, kind, filePath) {
  const result = optimize(source, {
    path: filePath,
    multipass: svgConfig.svgo?.multipass ?? true,
    plugins: svgoPlugins(kind),
  });

  let optimized = normalizeSvg(result.data);

  if (kind === "mono") {
    optimized = applyMonoCurrentColor(optimized);
  }

  return optimized;
}

function safeJson(value) {
  return JSON.stringify(value, null, 2)
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029");
}

function chunkString(value, size = 1000) {
  const text = String(value || "");
  const chunks = [];

  for (let i = 0; i < text.length; i += size) {
    chunks.push(text.slice(i, i + size));
  }

  return chunks;
}

function moduleSource(icon) {
  const bodyChunks = chunkString(icon.body);

  return `// Generated by scripts/generate-icons.mjs. Do not edit manually.

const body = [
${bodyChunks.map((part) => `  ${JSON.stringify(part)},`).join("\n")}
].join("");

const icon = {
  name: ${JSON.stringify(icon.name)},
  kind: ${JSON.stringify(icon.kind)},
  id: ${JSON.stringify(icon.id)},
  file: ${JSON.stringify(icon.file)},
  viewBox: ${JSON.stringify(icon.viewBox)},
  body,
};

export default icon;
`;
}

function manifestSource(icons) {
  const sorted = [...icons].sort((a, b) =>
    `${a.kind}:${a.name}`.localeCompare(`${b.kind}:${b.name}`)
  );

  const imports = sorted
    .map((icon, index) => `import icon${index} from "./${icon.kind}/${icon.name}.mjs";`)
    .join("\n");

  const entries = sorted
    .map((icon, index) => `  ${JSON.stringify(`${icon.kind}:${icon.name}`)}: icon${index},`)
    .join("\n");

  const byKind = svgConfig.kinds
    .map((kind) => {
      const kindIcons = sorted.filter((icon) => icon.kind === kind);

      const body = kindIcons
        .map(
          (icon) =>
            `    ${JSON.stringify(icon.name)}: icons[${JSON.stringify(`${kind}:${icon.name}`)}],`
        )
        .join("\n");

      return `  ${kind}: {\n${body}\n  },`;
    })
    .join("\n");

  return `// Generated by scripts/generate-icons.mjs. Do not edit manually.

${imports}

export const idPrefix = ${JSON.stringify(svgConfig.idPrefix)};
export const publicBase = ${JSON.stringify(svgConfig.publicBase)};

export const icons = {
${entries}
};

export const byKind = {
${byKind}
};

export function getIcon(name, kind = "mono") {
  return icons[\`\${kind}:\${name}\`] || null;
}

export default { idPrefix, publicBase, icons, byKind, getIcon };
`;
}

async function resetDir(dir) {
  await fs.rm(dir, { recursive: true, force: true });
  await fs.mkdir(dir, { recursive: true });
}

async function generateKind(kind) {
  const inputDir = fromRoot(svgConfig.input[kind]);
  const publicDir = fromRoot(svgConfig.output.public[kind]);
  const dataDir = fromRoot(svgConfig.output.data[kind]);

  await fs.mkdir(inputDir, { recursive: true });
  await resetDir(publicDir);
  await resetDir(dataDir);

  const files = await fg("*.svg", {
    cwd: inputDir,
    absolute: true,
    onlyFiles: true,
    unique: true,
  });

  const icons = [];

  for (const sourcePath of files.sort()) {
    const name = slugifyName(sourcePath);
    if (!name) continue;

    const id = `${svgConfig.idPrefix}${name}`;
    const outputFile = `/${toPosix(path.join("icons", kind, `${name}.svg`))}`;

    const raw = await fs.readFile(sourcePath, "utf8");

    // 1. Optimize first.
    const optimized = await optimizeSvg(raw, kind, sourcePath);

    // 2. Prefix ids after optimization, so gradients/masks/clipPaths are stable.
    const prefixed = prefixSvgIds(optimized, id);

    // 3. Extract only after optimized + prefixed output is ready.
    const parts = extractSvgParts(prefixed);

    const icon = {
      name,
      kind,
      id,
      file: outputFile,
      viewBox: parts.viewBox,
      body: parts.body,
    };

    await fs.writeFile(path.join(publicDir, `${name}.svg`), prefixed, "utf8");
    await fs.writeFile(path.join(dataDir, `${name}.mjs`), moduleSource(icon), "utf8");

    icons.push(icon);
  }

  return icons;
}

async function main() {
  const allIcons = [];

  for (const kind of svgConfig.kinds) {
    allIcons.push(...(await generateKind(kind)));
  }

  const manifestPath = fromRoot(svgConfig.output.data.manifest);
  await fs.mkdir(path.dirname(manifestPath), { recursive: true });
  await fs.writeFile(manifestPath, manifestSource(allIcons), "utf8");

  console.log(`Generated ${allIcons.length} icons.`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});