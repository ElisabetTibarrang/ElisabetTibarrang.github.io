#!/usr/bin/env node
// scripts/generate-brand.mjs

import fs from "node:fs/promises";
import fss from "node:fs";
import path from "node:path";
import process from "node:process";
import sharp from "sharp";
import { encode as encodeIco } from "sharp-ico";
import { optimize } from "svgo";
import brandConfig from "../src/config/brand.mjs";

const root = process.cwd();

function fromRoot(...parts) {
  return path.join(root, ...parts.filter(Boolean));
}

function toPublicPath(absPath) {
  return `/${path.relative(fromRoot("public"), absPath).replaceAll(path.sep, "/")}`;
}

function resolveInput(inputPath) {
  if (!inputPath || typeof inputPath !== "string") return null;
  const abs = path.isAbsolute(inputPath) ? inputPath : fromRoot(inputPath);
  return fss.existsSync(abs) ? abs : null;
}

async function ensureDir(dir) {
  await fs.mkdir(dir, { recursive: true });
}

function stripSvg(svg) {
  return String(svg || "")
    .replace(/<\?xml[^>]*?\?>/gi, "")
    .replace(/<!doctype[^>]*?>/gi, "")
    .trim();
}

async function optimizeSvgFile(inputPath, outputPath) {
  const src = resolveInput(inputPath);
  if (!src) return null;

  const raw = await fs.readFile(src, "utf8");
  let svg = stripSvg(raw);

  if (brandConfig.svgo?.enabled !== false) {
    try {
      const result = optimize(svg, {
        path: src,
        multipass: brandConfig.svgo?.multipass ?? false,
        plugins: brandConfig.svgo?.plugins || ["preset-default", "removeDimensions"],
      });

      if (result?.data?.includes("<svg")) {
        svg = stripSvg(result.data);
      }
    } catch (error) {
      console.warn(`⚠️ SVGO failed for ${src}. Copying original SVG.`, error?.message || error);
    }
  }

  await ensureDir(path.dirname(outputPath));
  await fs.writeFile(outputPath, svg, "utf8");

  return toPublicPath(outputPath);
}

async function svgToPng(inputSvg, outputPng, size) {
  const src = resolveInput(inputSvg);
  if (!src) return null;

  await ensureDir(path.dirname(outputPng));

  await sharp(src)
    .resize(size, size, {
      fit: "contain",
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    })
    .png({ compressionLevel: 9 })
    .toFile(outputPng);

  return toPublicPath(outputPng);
}

async function generateIco(inputSvg, outputIco) {
  const src = resolveInput(inputSvg);
  if (!src) return null;

  await ensureDir(path.dirname(outputIco));

  const pngBuffer = await sharp(src)
    .resize(64, 64, {
      fit: "contain",
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    })
    .png({ compressionLevel: 9 })
    .toBuffer();

  const icoBuffer = await encodeIco([pngBuffer]);
  await fs.writeFile(outputIco, icoBuffer);

  return "/favicon.ico";
}

function manifestModuleSource(data) {
  return `// Generated by scripts/generate-brand.mjs. Do not edit manually.

export const brand = ${JSON.stringify(data, null, 2)};

export default brand;
`;
}

async function writeWebManifest(data) {
  const icons = [];

  if (data.icons.android192) {
    icons.push({
      src: data.icons.android192,
      sizes: "192x192",
      type: "image/png",
    });
  }

  if (data.icons.android512) {
    icons.push({
      src: data.icons.android512,
      sizes: "512x512",
      type: "image/png",
    });
  }

  if (data.icons.appleTouchIcon) {
    icons.push({
      src: data.icons.appleTouchIcon,
      sizes: "180x180",
      type: "image/png",
    });
  }

  if (data.logos.faviconSvg) {
    icons.push({
      src: data.logos.faviconSvg,
      sizes: "any",
      type: "image/svg+xml",
    });
  }

  const manifest = {
    name: brandConfig.siteName || "AstroWebTheme",
    short_name: brandConfig.shortName || brandConfig.siteName || "AstroWeb",
    description: brandConfig.description || "",
    start_url: "/",
    scope: "/",
    display: "standalone",
    background_color: brandConfig.backgroundColor || "#ffffff",
    theme_color: brandConfig.themeColor || "#000000",
    icons,
  };

  const out = fromRoot(brandConfig.output.webManifest);
  await ensureDir(path.dirname(out));
  await fs.writeFile(out, JSON.stringify(manifest, null, 2), "utf8");

  return "/manifest.webmanifest";
}

async function main() {
  const publicBrandDir = fromRoot(brandConfig.output.publicBrandDir);
  const publicDir = fromRoot("public");
  const dataManifest = fromRoot(brandConfig.output.dataManifest);

  await ensureDir(publicBrandDir);
  await ensureDir(path.dirname(dataManifest));

  const input = {
    logoFull: brandConfig.input?.logoFull || null,
    logoIcon: brandConfig.input?.logoIcon || null,
    logoText: brandConfig.input?.logoText || null,
    favicon: brandConfig.input?.favicon || null,
  };

  const logoFullSource = resolveInput(input.logoFull);
  const logoIconSource = resolveInput(input.logoIcon);
  const logoTextSource = resolveInput(input.logoText);
  const faviconSource = resolveInput(input.favicon) || logoIconSource || logoFullSource;

  const logos = {
    logoFull: logoFullSource
      ? await optimizeSvgFile(logoFullSource, path.join(publicBrandDir, "logo-full.svg"))
      : null,

    logoIcon: logoIconSource
      ? await optimizeSvgFile(logoIconSource, path.join(publicBrandDir, "logo-icon.svg"))
      : null,

    logoText: logoTextSource
      ? await optimizeSvgFile(logoTextSource, path.join(publicBrandDir, "logo-text.svg"))
      : null,

    faviconSvg: faviconSource
      ? await optimizeSvgFile(faviconSource, path.join(publicDir, "favicon.svg"))
      : null,
  };

  const icons = {
    appleTouchIcon: faviconSource
      ? await svgToPng(faviconSource, path.join(publicDir, "apple-touch-icon.png"), 180)
      : null,

    android192: faviconSource
      ? await svgToPng(faviconSource, path.join(publicDir, "android-chrome-192x192.png"), 192)
      : null,

    android512: faviconSource
      ? await svgToPng(faviconSource, path.join(publicDir, "android-chrome-512x512.png"), 512)
      : null,

    favicon32: faviconSource
      ? await svgToPng(faviconSource, path.join(publicDir, "favicon-32x32.png"), 32)
      : null,

    faviconIco: faviconSource
      ? await generateIco(faviconSource, path.join(publicDir, "favicon.ico"))
      : null,
  };

  if (!faviconSource) {
    console.warn(
      "⚠️ No favicon source found. Add src/assets/brand/favicon.svg, logo-icon.svg, or logo-full.svg when ready."
    );
  }

  const data = {
    siteName: brandConfig.siteName || "AstroWebTheme",
    shortName: brandConfig.shortName || "AstroWeb",
    description: brandConfig.description || "",
    siteUrl: brandConfig.siteUrl || "",
    themeColor: brandConfig.themeColor || "#000000",
    backgroundColor: brandConfig.backgroundColor || "#ffffff",
    publicBase: brandConfig.publicBase || "/brand",
    logos,
    icons,
    webManifest: null,
    generatedAt: new Date().toISOString(),
  };

  data.webManifest = await writeWebManifest(data);

  await fs.writeFile(dataManifest, manifestModuleSource(data), "utf8");

  console.log("Generated brand assets.");
}

main().catch((error) => {
  console.error("Brand generation failed:", error);
  process.exitCode = 1;
});