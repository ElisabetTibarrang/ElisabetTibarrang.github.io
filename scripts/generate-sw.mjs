#!/usr/bin/env node
// scripts/generate-sw.mjs

import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const root = process.cwd();

function fromRoot(...parts) {
  return path.join(root, ...parts);
}

async function ensureDir(dir) {
  await fs.mkdir(dir, { recursive: true });
}

async function ensureOfflineHtml() {
  const file = fromRoot("public", "offline.html");

  try {
    await fs.access(file);
    return;
  } catch {
    // create fallback
  }

  const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width,initial-scale=1" />
  <title>Offline</title>
  <style>
    body {
      margin: 0;
      min-height: 100vh;
      display: grid;
      place-items: center;
      font-family: system-ui, sans-serif;
      background: #fff;
      color: #111;
      text-align: center;
      padding: 2rem;
    }
  </style>
</head>
<body>
  <main>
    <h1>You are offline</h1>
    <p>Please check your internet connection and try again.</p>
  </main>
</body>
</html>`;

  await fs.writeFile(file, html, "utf8");
}

function swSource() {
  return `// Generated by scripts/generate-sw.mjs

const CACHE_NAME = "astrowebtheme-free-runtime-v1";
const OFFLINE_URL = "/offline.html";

const CACHEABLE_DESTINATIONS = new Set([
  "style",
  "script",
  "font",
  "image",
]);

const CACHEABLE_EXTENSIONS = [
  ".css",
  ".js",
  ".mjs",
  ".woff2",
  ".woff",
  ".png",
  ".jpg",
  ".jpeg",
  ".webp",
  ".avif",
  ".svg",
  ".ico",
  ".json",
  ".webmanifest",
];

function isSameOrigin(url) {
  return url.origin === self.location.origin;
}

function isSkippable(url) {
  const path = url.pathname.toLowerCase();

  return (
    path.includes("csp-report") ||
    path.includes("report-uri") ||
    path.includes("/report") ||
    path.includes("/reports")
  );
}

function hasCacheableExtension(pathname) {
  const lower = pathname.toLowerCase();
  return CACHEABLE_EXTENSIONS.some((ext) => lower.endsWith(ext));
}

function isCacheableRequest(request, url) {
  if (!request || request.method !== "GET") return false;
  if (!isSameOrigin(url)) return false;
  if (isSkippable(url)) return false;

  return (
    CACHEABLE_DESTINATIONS.has(request.destination) ||
    hasCacheableExtension(url.pathname)
  );
}

function responseAllowsCache(response) {
  if (!response || !response.ok) return false;

  const cacheControl = response.headers.get("cache-control") || "";
  const lower = cacheControl.toLowerCase();

  if (lower.includes("no-store")) return false;
  if (lower.includes("private")) return false;

  return (
    lower.includes("public") ||
    lower.includes("max-age") ||
    lower.includes("immutable")
  );
}

self.addEventListener("install", (event) => {
  self.skipWaiting();

  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => {
      return cache.add(OFFLINE_URL).catch(() => {});
    })
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) => {
      return Promise.all(
        keys.map((key) => {
          if (key !== CACHE_NAME && key.startsWith("astrowebtheme-free-")) {
            return caches.delete(key);
          }
          return null;
        })
      );
    }).then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (!request || request.method !== "GET") return;

  const url = new URL(request.url);
  if (!isSameOrigin(url)) return;
  if (isSkippable(url)) return;

  if (request.mode === "navigate") {
    event.respondWith(networkFirstNavigation(request));
    return;
  }

  if (isCacheableRequest(request, url)) {
    event.respondWith(cacheFirst(request));
  }
});

async function networkFirstNavigation(request) {
  try {
    const response = await fetch(request);
    return response;
  } catch {
    return (await caches.match(OFFLINE_URL)) || new Response("Offline", { status: 503 });
  }
}

async function cacheFirst(request) {
  const cache = await caches.open(CACHE_NAME);
  const cached = await cache.match(request);

  if (cached) return cached;

  const response = await fetch(request);

  if (responseAllowsCache(response)) {
    cache.put(request, response.clone()).catch(() => {});
  }

  return response;
}
`;
}

async function main() {
  const publicDir = fromRoot("public");
  await ensureDir(publicDir);
  await ensureOfflineHtml();

  await fs.writeFile(fromRoot("public", "sw.js"), swSource(), "utf8");

  console.log("Generated public/sw.js");
}

main().catch((error) => {
  console.error("SW generation failed:", error);
  process.exitCode = 1;
});