// scripts/generate-content-config.mjs
import fs from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = process.cwd();

const PAGES_CONFIG = path.join(ROOT, "src/config/pages.mjs");
const LIVE_CONFIG = path.join(ROOT, "src/config/live.mjs");

const CONTENT_CONFIG_OUT = path.join(ROOT, "src/content.config.mjs");
const LIVE_CONFIG_OUT = path.join(ROOT, "src/live.config.mjs");

const TAG = "// AUTO-GENERATED BY AstroWEB v2 — DO NOT EDIT BY HAND";

const DRY_RUN = process.argv.includes("--dry-run");
const FORCE = process.argv.includes("--force");

function rel(p) {
  return path.relative(ROOT, p).replaceAll("\\", "/");
}

async function loadModule(file) {
  try {
    return await import(`${pathToFileURL(file).href}?t=${Date.now()}`);
  } catch {
    console.warn(`[warn] Could not load ${rel(file)}. Using empty config.`);
    return {};
  }
}

function toIdentifier(value) {
  const raw = String(value || "").trim();

  if (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(raw)) return raw;

  return raw
    .replace(/[-\s]+([a-zA-Z0-9])/g, (_, c) => c.toUpperCase())
    .replace(/[^A-Za-z0-9_$]+/g, "_")
    .replace(/^([^A-Za-z_$])/, "_$1");
}

function unique(values) {
  return [...new Set(values.filter(Boolean))];
}

function uniqueSorted(values) {
  return unique(values).sort((a, b) => String(a).localeCompare(String(b)));
}

function normalizeSource(cfg = {}, fallbackKey = "") {
  const source = cfg.source && typeof cfg.source === "object" ? cfg.source : {};

  return {
    mode: source.mode || "static",
    dir: source.dir || cfg.dir || cfg.base || fallbackKey,
    contentDir:
      source.contentDir ||
      `src/content/${source.dir || cfg.dir || cfg.base || fallbackKey}`,
    formats: Array.isArray(source.formats) ? source.formats : ["md", "mdx"],
  };
}

function classifyCollection(key, cfg = {}) {
  if (cfg.kind) return cfg.kind;

  const k = String(key).toLowerCase();
  const dir = String(cfg?.dir || cfg?.base || key).toLowerCase();

  if (k === "service" || dir === "service" || dir === "services") return "serviceArticle";
  if (k === "videos" || dir === "videos") return "mediaVideo";
  if (k === "audio" || dir === "audio") return "mediaAudio";
  if (k === "team" || dir === "team") return "team";
  if (k === "review" || dir === "review" || dir === "reviews") return "reviewData";
  if (k === "researcher-profile" || dir === "researcher-profile") return "researcherProfile";
  if (k === "publications" || dir === "publications") return "publication";
  if (k === "live-posts" || k === "liveposts" || dir === "live-posts") return "liveArticle";

  return "article";
}

function schemaForKind(kind) {
  switch (kind) {
    case "serviceArticle":
      return "serviceArticleSchema";
    case "mediaVideo":
      return "videoSchema";
    case "mediaAudio":
      return "audioSchema";
    case "team":
      return "teamSchema";
    case "reviewData":
      return "reviewSchema";
    case "researcherProfile":
      return "researcherProfileSchema";
    case "publication":
      return "publicationSchema";
    case "liveArticle":
      return "liveArticleSchema";
    case "article":
    default:
      return "articleSchema";
  }
}

function importForSchema(schemaName) {
  switch (schemaName) {
    case "articleSchema":
      return `import { articleSchema } from "./schema/article.mjs";`;
    case "serviceArticleSchema":
      return `import { serviceArticleSchema } from "./schema/service.mjs";`;
    case "videoSchema":
    case "audioSchema":
      return `import { videoSchema, audioSchema } from "./schema/media.mjs";`;
    case "teamSchema":
      return `import { teamSchema } from "./schema/team.mjs";`;
    case "reviewSchema":
      return `import { reviewSchema } from "./schema/review.mjs";`;
    case "researcherProfileSchema":
      return `import { researcherProfileSchema } from "./schema/researcher-profile.mjs";`;
    case "publicationSchema":
      return `import { publicationSchema } from "./schema/publications.mjs";`;
    case "liveArticleSchema":
      return `import { liveArticleSchema } from "./schema/live.mjs";`;
    default:
      return "";
  }
}

function extensionOptionsForCollection(collectionKey, cfg = {}, fieldCollections = {}) {
  const taxonomy = {};

  for (const [fieldKey, fieldCfg] of Object.entries(fieldCollections || {})) {
    if (!fieldCfg?.enabled) continue;

    const fieldName = fieldCfg.fieldName || fieldKey;

    if (Array.isArray(fieldCfg.collections) && fieldCfg.collections.length) {
      taxonomy[fieldName] = fieldCfg.collections.includes(collectionKey);
      continue;
    }

    taxonomy[fieldName] =
      cfg?.taxonomy?.[fieldName] === true ||
      cfg?.taxonomy?.[fieldKey] === true ||
      cfg[fieldName] === true ||
      cfg[fieldKey] === true;
  }

  return {
    taxonomy,
    features: cfg.features || {},
    relations: {
      ...(cfg.relations || {}),
      team: cfg?.relations?.team === true || cfg.authors === true,
    },
    assets: cfg.assets || {},
    authors: cfg.authors === true,
  };
}

function patternForSource(source = {}, kind = "") {
  const formats =
    Array.isArray(source.formats) && source.formats.length
      ? source.formats
      : kind === "reviewData"
        ? ["json"]
        : ["md", "mdx"];

  if (formats.length === 1) return `**/*.${formats[0]}`;

  return `**/*.{${formats.join(",")}}`;
}

function shouldIncludeInContentConfig(cfg = {}) {
  const source = cfg.source && typeof cfg.source === "object" ? cfg.source : {};
  return source.mode !== "live";
}

function buildContentConfig({ collections = {}, fieldCollections = {} }) {
  const enabledEntries = Object.entries(collections).filter(
    ([, cfg]) => cfg?.enabled !== false && shouldIncludeInContentConfig(cfg)
  );

  const usedSchemas = new Set();
  const collectionBlocks = [];
  const exportLines = [];

  for (const [key, cfg] of enabledEntries) {
    const kind = classifyCollection(key, cfg);
    const schemaName = schemaForKind(kind);
    const varName = toIdentifier(key);
    const source = normalizeSource(cfg, key);
    const pattern = patternForSource(source, kind);
    const extensionOptions = extensionOptionsForCollection(key, cfg, fieldCollections);

    usedSchemas.add(schemaName);

    const schemaExpr = `extendSchema(${schemaName}, ${JSON.stringify(extensionOptions, null, 2)})`;

    collectionBlocks.push(`const ${varName} = defineCollection({
  loader: glob({
    base: "./${source.contentDir.replace(/^\.?\//, "")}",
    pattern: "${pattern}",
  }),
  schema: ${schemaExpr},
});`);

    exportLines.push(
      key === varName ? `  ${varName},` : `  ${JSON.stringify(key)}: ${varName},`
    );
  }

  const imports = uniqueSorted([...usedSchemas].map(importForSchema)).filter(Boolean);

  return `${TAG}

import { defineCollection } from "astro:content";
import { glob } from "astro/loaders";

import { extendSchema } from "./schema/base.mjs";
${imports.join("\n")}

${collectionBlocks.join("\n\n")}

export const collections = {
${exportLines.join("\n")}
};
`;
}

function schemaImportForLiveSchema(schemaName) {
  switch (schemaName) {
    case "liveProfileSchema":
      return "liveProfileSchema";
    case "livePublicationSchema":
      return "livePublicationSchema";
    case "liveArticleSchema":
    default:
      return "liveArticleSchema";
  }
}

function buildLiveEntriesFromPagesCollections(collections = {}) {
  const out = {};

  for (const [key, cfg] of Object.entries(collections || {})) {
    if (!cfg?.enabled) continue;

    const source = cfg.source && typeof cfg.source === "object" ? cfg.source : {};
    if (source.mode !== "live") continue;

    const kind = classifyCollection(key, cfg);

    let schema = "liveArticleSchema";
    if (kind === "researcherProfile") schema = "liveProfileSchema";
    if (kind === "publication") schema = "livePublicationSchema";

    out[key] = {
      ...cfg,
      schema,
    };
  }

  return out;
}

function mergeLiveCollections(pagesLive = {}, explicitLive = {}) {
  return {
    ...pagesLive,
    ...explicitLive,
  };
}

function buildLiveConfig({ liveCollections = {} }) {
  const enabledEntries = Object.entries(liveCollections).filter(
    ([, cfg]) => cfg?.enabled === true
  );

  const usedLiveSchemas = uniqueSorted(
    enabledEntries.map(([, cfg]) => schemaImportForLiveSchema(cfg.schema))
  );

  const blocks = [];
  const exportLines = [];

  for (const [key, cfg] of enabledEntries) {
    const varName = toIdentifier(key);
    const schemaName = schemaImportForLiveSchema(cfg.schema);

    blocks.push(`const ${varName} = defineLiveCollection({
  loader: createLiveLoader(${JSON.stringify(cfg, null, 2)}),
  schema: schemaMap.${schemaName},
});`);

    exportLines.push(
      key === varName ? `  ${varName},` : `  ${JSON.stringify(key)}: ${varName},`
    );
  }

  return `${TAG}

import { defineLiveCollection } from "astro:content";
import { createLiveLoader } from "./loaders/live.mjs";
import { ${usedLiveSchemas.length ? usedLiveSchemas.join(", ") : "liveArticleSchema"} } from "./schema/live.mjs";

const schemaMap = {
  ${usedLiveSchemas.length ? usedLiveSchemas.join(",\n  ") : "liveArticleSchema"},
};

${blocks.join("\n\n")}

export const collections = {
${exportLines.join("\n")}
};
`;
}

async function safeWrite(file, content) {
  let previous = "";

  try {
    previous = await fs.readFile(file, "utf8");
  } catch {}

  if (previous && !previous.includes(TAG) && !FORCE) {
    console.log(`[skip] ${rel(file)} exists and is not generator-owned`);
    return;
  }

  if (DRY_RUN) {
    console.log(`[dry-run] would write ${rel(file)}`);
    return;
  }

  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, content, "utf8");
  console.log(`[write] ${rel(file)}`);
}

async function main() {
  const pagesMod = await loadModule(PAGES_CONFIG);
  const liveMod = await loadModule(LIVE_CONFIG);

  const pagesCollections = pagesMod.collections || {};
  const fieldCollections = pagesMod.fieldCollections || {};

  const pagesLiveCollections = buildLiveEntriesFromPagesCollections(pagesCollections);
  const liveCollections = mergeLiveCollections(
    pagesLiveCollections,
    liveMod.liveCollections || {}
  );

  const contentSource = buildContentConfig({
    collections: pagesCollections,
    fieldCollections,
  });

  const liveSource = buildLiveConfig({
    liveCollections,
  });

  await safeWrite(CONTENT_CONFIG_OUT, contentSource);
  await safeWrite(LIVE_CONFIG_OUT, liveSource);
}

main().catch((err) => {
  console.error("[generate-content-config] failed:", err);
  process.exit(1);
});