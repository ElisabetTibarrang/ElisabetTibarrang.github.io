#!/usr/bin/env node
// scripts/generate-live-config.mjs
// Generates Astro v7-compatible src/live.config.mjs for runtime live collections.

import fs from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = process.cwd();
const PAGES_FILE = path.join(ROOT, 'src/site/config/pages.mjs');
const OUT = path.join(ROOT, 'src/live.config.mjs');
const TAG = '// AUTO-GENERATED BY AstroWEB v2: live.config.mjs — DO NOT EDIT BY HAND';
const FORCE = process.argv.includes('--force');
const DRY = process.argv.includes('--dry-run');
const SCHEMA_IMPORT = './site/content/schemas/index.mjs';
const LOADER_IMPORT = './site/loaders/live.mjs';

const schemaForKind = { liveArticle: 'liveArticleSchema', article: 'baseSchema', publication: 'publicationSchema', researcherProfile: 'researcherProfileSchema' };

function ident(value) {
  const s = String(value).replace(/[-\s]+([a-zA-Z0-9])/g, (_, c) => c.toUpperCase()).replace(/[^A-Za-z0-9_$]/g, '_');
  return /^[A-Za-z_$]/.test(s) ? s : `_${s}`;
}

const mod = await import(`${pathToFileURL(PAGES_FILE).href}?t=${Date.now()}`);
const live = Object.entries(mod.collections || {}).filter(([, cfg]) => cfg?.enabled !== false && cfg?.source?.mode === 'live');

const usedSchemas = new Set();
const usedLoaders = new Set();
const blocks = [];
const exports = [];

for (const [key, cfg] of live) {
  const varName = ident(key);
  const schemaName = schemaForKind[cfg.kind] || 'liveArticleSchema';
  const loaderKey = cfg.source?.loaderKey;
  if (!loaderKey) throw new Error(`Live collection ${key} missing source.loaderKey`);
  usedSchemas.add(schemaName);
  usedLoaders.add(loaderKey);
  blocks.push(`const ${varName} = defineLiveCollection({\n  loader: ${loaderKey}(${JSON.stringify(cfg.source.options || {}, null, 2)}),\n  schema: ${schemaName},\n});`);
  exports.push(key === varName ? `  ${varName},` : `  ${JSON.stringify(key)}: ${varName},`);
}

const source = `${TAG}\n// Astro v7 live collections. Keep custom loader implementations in src/site/loaders/live.mjs.\n\nimport { defineLiveCollection } from 'astro:content';\nimport {\n${[...usedSchemas].map((x) => `  ${x},`).join('\n')}\n} from ${JSON.stringify(SCHEMA_IMPORT)};\nimport {\n${[...usedLoaders].map((x) => `  ${x},`).join('\n')}\n} from ${JSON.stringify(LOADER_IMPORT)};\n\n${blocks.join('\n\n') || '// No enabled live collections in src/site/config/pages.mjs.'}\n\nexport const collections = {\n${exports.join('\n')}\n};\n`;

try {
  const prev = await fs.readFile(OUT, 'utf8');
  if (!FORCE && !prev.includes(TAG)) {
    console.log(`[live-config] skip foreign file: ${path.relative(ROOT, OUT)}`);
    process.exit(0);
  }
  if (prev === source) {
    console.log('[live-config] unchanged');
    process.exit(0);
  }
} catch {}

if (DRY) {
  console.log(`[live-config] dry-run write: ${path.relative(ROOT, OUT)}`);
} else {
  await fs.writeFile(OUT, source, 'utf8');
  console.log(`[live-config] wrote ${path.relative(ROOT, OUT)}`);
}
